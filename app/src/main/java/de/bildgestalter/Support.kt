/** Text für die aktuelle Sprache (fehlt die Sprache: Englisch). */
fun supportText(): String {
    val c = Lang.code
    return SUPPORT[SUPPORT_ALIAS[c] ?: c] ?: SUPPORT.getValue("en")
}

/** Zeile 1: erstes Wort + Herz, Zeile 2: Rest + Daumen. Ohne Leerzeichen: alles in einer Zeile. */
fun supportLabel(text: String): String {
    val i = text.indexOf(' ')
    return if (i > 0) {
        text.substring(0, i) + " \u2764\uFE0F\n" + text.substring(i + 1) + " \uD83D\uDC4D"
    } else {
        text + " \u2764\uFE0F\uD83D\uDC4D"
    }
}
